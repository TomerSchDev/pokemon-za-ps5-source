"""Generate src/capabilities_generated.inc from the generator's capabilities file (port/rando-v3/capabilities.json).

The launcher only offers an option when the generator of THIS build writes it. The generator work (port/rando-v3) is
done by another agent; its capabilities.json says, per option id of ui_model.cpp, which option ids (levels) or which
numeric range it supports. Until that file exists, nothing beyond the model's own Avail::Now entries is offered
(the generated table is empty and the model falls back to its static availability).

Accepted shapes (lenient, so the other agent's schema fits without a round trip):
  {"schema": 1, "options": {"wild_mode": {"supported": ["off", "zones", "random"]},
                            "starter_level": {"range": [5, 50]},
                            "trainer_levels": ["vanilla", "plus10"]}}
  {"wild_mode": ["off", "random"], ...}                      (the mapping at the top level)
  {"options": {"wild_mode": {"levels": [...]}}}, "values", "ids", "choices" are read like "supported";
  a numeric row is shipped when it has "range", "min"/"max", or "supported": ["*"].
Usage: gen-capabilities.py [capabilities.json] [out .inc]
"""
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
src = Path(sys.argv[1]) if len(sys.argv) > 1 else root.parent / 'rando-v3' / 'capabilities.json'
out = Path(sys.argv[2]) if len(sys.argv) > 2 else root / 'src' / 'capabilities_generated.inc'

entries = []
present = src.is_file()
source_note = 'none (port/rando-v3/capabilities.json absent: only the model\'s own Avail::Now options are offered)'
if present:
    doc = json.loads(src.read_text(encoding='utf-8-sig'))
    mapping = doc
    for key in ('options', 'rows', 'capabilities'):
        if isinstance(doc, dict) and isinstance(doc.get(key), dict):
            mapping = doc[key]
            break
    if not isinstance(mapping, dict):
        sys.exit('capabilities.json: expected an object of option id -> supported options')
    for row_id, spec in sorted(mapping.items()):
        if row_id in ('schema', 'version', 'generated', 'notes', 'generator'):
            continue
        supported = []
        if isinstance(spec, list):
            supported = spec
        elif isinstance(spec, dict):
            for key in ('supported', 'levels', 'values', 'ids', 'choices', 'options'):
                if isinstance(spec.get(key), list):
                    supported = spec[key]
                    break
            if spec.get('supported') is True:  # text rows: "supported": true
                supported = ['*']
            rng = spec.get('supported_range', spec.get('range'))
            if isinstance(rng, dict):
                rng = [rng.get('min'), rng.get('max')]
            if isinstance(rng, list) and len(rng) == 2 and all(isinstance(v, (int, float)) for v in rng) and rng[0] < rng[1]:
                supported = supported + ['*']  # a numeric row with a real range to choose from
            elif 'min' in spec and 'max' in spec and spec['min'] < spec['max']:
                supported = supported + ['*']
        elif isinstance(spec, bool):
            supported = ['*'] if spec else []
        for opt in supported:
            if isinstance(opt, dict):
                opt = opt.get('id', '')
            opt = str(opt)
            if not opt or any(c in opt for c in '"\\\n'):
                sys.exit('capabilities.json: bad option id %r for %s' % (opt, row_id))
            entries.append((row_id, opt))
    try:
        source_note = src.resolve().relative_to(root.parents[1]).as_posix()  # relative to the repo (ASCII)
    except ValueError:
        source_note = src.name
lines = ['// GENERATED by tools/gen-capabilities.py; source: %s' % source_note,
         '// (row id, option id) pairs the generator of this build supports; "*" = every value of a numeric row.',
         'static const ui::model::CapEntry kCaps[] = {']
for row_id, opt in entries:
    lines.append('    {"%s", "%s"},' % (row_id, opt))
lines.append('    {nullptr, nullptr},')
lines.append('};')
lines.append('static const bool kCapsPresent = %s;' % ('true' if present else 'false'))
out.write_text('\n'.join(lines) + '\n', encoding='ascii', newline='\n')
print('capabilities: %s, %d entries -> %s' % ('present' if present else 'absent', len(entries), out))
