"""Versioned randomizer overlay and curated source/evidence; no full game assets."""
from pathlib import Path
import argparse, datetime, importlib.util, json, re, shutil

ROOT=Path(__file__).resolve().parents[2]
spec=importlib.util.spec_from_file_location('archive_util',ROOT/'port/title/package-r14-deliverables.py')
util=importlib.util.module_from_spec(spec);spec.loader.exec_module(util)

def main():
    p=argparse.ArgumentParser()
    p.add_argument('revision');p.add_argument('expected_sha256');p.add_argument('report',type=Path)
    p.add_argument('--repair-backup',type=Path)
    a=p.parse_args()
    assert re.fullmatch(r'r[0-9]+',a.revision) and re.fullmatch(r'[0-9a-f]{64}',a.expected_sha256)
    app=ROOT/'artifacts'/('randomizer-'+a.revision)/'PPSA91762'
    with (app/'eboot.bin').open('rb') as f: assert util.sha(f)==a.expected_sha256
    dest=ROOT/'deliverables'/('ZA-Native-Randomizer-'+a.revision+'-'+datetime.datetime.now().strftime('%Y%m%d-%H%M%S'))
    dest.mkdir()
    shutil.copyfile(a.report,dest/a.report.name)
    files={'PPSA91762/'+f.relative_to(app).as_posix():f for f in app.rglob('*') if f.is_file()}
    assert not any('/game/' in name for name in files)
    records=[util.archive(dest/('ZA-Native-Randomizer-'+a.revision+'-Overlay.zip'),files,{'README.txt':
        'Overlay for the separate PPSA91762 randomizer. Consult the report for installation and hardware-test status.\n'
        'NOT a standalone game: existing 2.0.2 + merged DLC assets (~6 GB) are omitted.\n'
        'Preserve game/, download0 saves, active run and newer shader-cache entries.\n'
        'Never restore onto PPSA91761 or overwrite active gameplay. Close the app first.\n'
        'The initial pipeline cache is from this PS5/RADV build and is only seeded on first boot.\n'
        'New seeds are generated by the console menu without recompiling the game.\n'
        'Unknown shaders still require the bounded PC shader helper. This snapshot is not full-game coverage.\n'
    })]
    sources={}
    for directory in ['port/randomizer','port/title','port/sdl3-shim','port/vk-loader','port/ffmpeg-stubs','port/shaderc-cache']:
        for f in (ROOT/directory).rglob('*'):
            if f.is_file() and f.suffix in {'.c','.h','.cpp','.hpp','.py','.sh','.ps1','.mk','.txt','.md','.json','.patch','.S'}:
                sources['source/'+f.relative_to(ROOT).as_posix()]=f
    sources['source/run_r3.py']=ROOT/'run_r3.py'
    for f in (ROOT/'evidence').glob('randomizer*'):
        if f.is_file() and f.suffix in {'.json','.txt','.log'}: sources['evidence/'+f.name]=f
        if f.is_dir():
            for name in ['manifest.json','verification.json','report.json','inventory.json','boss-graph.json','absol-case-study.json','candidate-packs.json']:
                q=f/name
                if q.is_file(): sources['evidence/'+f.name+'/'+name]=q
    texts={'README.txt':'Randomizer source and targeted evidence. Runtime baseline is the separate r14 hardware handoff.\nNo SDKs, credential stores, full game data or generated game C are included.\n'}
    for f in (ROOT/'evidence').glob('title-randomizer-*.klog.log'):
        lines=f.read_text(encoding='utf-8',errors='replace').splitlines()
        texts['evidence/'+f.name]='\n'.join(s for s in lines if s.startswith(('[za-','[zarecomp]','[pipeline-cache]','[ps5]')))
    records.append(util.archive(dest/'ZA-Native-Randomizer-Source-and-Evidence.zip',sources,texts))
    if a.repair_backup:
        repair=a.repair_backup.resolve();assert repair.parent==ROOT/'evidence' and repair.name.startswith('randomizer-r14-repair-')
        save_files={'original/'+f.relative_to(repair/'original').as_posix():f for f in (repair/'original').rglob('*') if f.is_file()}
        for name in ('original-active.json','verification.json'):
            save_files[name]=repair/name
        records.append(util.archive(dest/'ZA-Native-Randomizer-Pre-Repair-Backup.zip',save_files,{
            'README.txt':'Fresh backup taken while the original run was closed at the launcher menu, before r15 repair.\n'
            'The original run is also retained on the console. Do not restore this over later gameplay progress.\n'}))
    backup=ROOT/'evidence/randomizer-saved-before-close-20261027-204730Z'
    if backup.is_dir():
        names=['main','active.json','report.json','snapshot.json']
        save_files={'r6-historical/'+name:backup/name for name in names if (backup/name).is_file()}
        if 'r6-historical/main' in save_files:
            records.append(util.archive(dest/'ZA-Native-Randomizer-Historical-Save-Backup.zip',save_files,{
                'README.txt':'Historical snapshot of the first Gengar run before the Continue test, not current progress.\n'
                'Never restore over a newer save. This belongs only to PPSA91762, not stock PPSA91761.\n'
                'The run identifier and saved-file hashes are in the accompanying JSON records.\n'}))
    (dest/'DELIVERABLES-VERIFIED.json').write_text(json.dumps({'revision':a.revision,'native_sha256':a.expected_sha256,'archives':records},indent=2),encoding='utf-8')
    print(str(dest))

if __name__=='__main__': main()
