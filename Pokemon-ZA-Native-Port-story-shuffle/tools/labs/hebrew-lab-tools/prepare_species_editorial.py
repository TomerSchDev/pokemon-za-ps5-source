def main():
    out=LAB/'translations/species-editorial-20261030-r1.json'
    if out.exists(): raise FileExistsError(out)
    glossary={r['english']:r['hebrew'] for r in csv.DictReader((LAB/'glossary.tsv').open(encoding='utf-8-sig'),delimiter='\t') if r['category']=='pokemon'}
    edits={int(i):he for i,he in (line.split('|') for line in EDITS.splitlines() if line)}
    # Avoid introducing niqqud unsupported by the game's font atlas.
    edits[580]='דאקלט'
    current={}
    for name in MODULES:
        module=load_module(name)
        for table in getattr(module,'TABLES',[module]): current.update(table.TERMS)
    file='ik_message/dat/English/common/monsname.dat'
    rows=[]
    for r in iter_tm(LAB/'memory/english-source.jsonl'):
        if r['file']!=file or not r['requires_translation']: continue
        he=edits.get(r['line_index'],glossary.get(r['source']))
        if r['source'] in current: he=current[r['source']]
        if not he: raise ValueError(r)
        rows.append(dict(index=r['line_index'],source=r['source'],he=he))
    assert len(rows)==1026
    data=dict(status='assistant_editorial_spelling_review; not official Hebrew names; visual QA pending',tables={file:rows})
    out.write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print(dict(rows=len(rows),explicit_spelling_edits=len(edits)))

if __name__=='__main__':main()
