"""Generate za_music_plan.cpp (the plan text as a byte array plus its SHA-256) for the title build.
Usage: embed_plan.py PLAN.json OUT.cpp [EXPECTED_SHA256]. The output is game-derived: keep it in the build work dir."""
import hashlib
import sys

plan, out = sys.argv[1], sys.argv[2]
data = open(plan, 'rb').read()
digest = hashlib.sha256(data).hexdigest()
if len(sys.argv) > 3 and sys.argv[3] != digest:
    sys.exit('plan SHA-256 %s does not match the pinned %s' % (digest, sys.argv[3]))
if b'\0' in data:
    sys.exit('plan contains NUL')
rows = []
for i in range(0, len(data), 24):
    rows.append(''.join('%d,' % b for b in data[i:i + 24]))
text = ('// GENERATED by port/rando-music/tools/embed_plan.py - game-derived music plan, not for git.\n'
        '#include "za_music_plan.hpp"\n'
        'namespace za::native {\n'
        'static const char plan[%d] = {\n%s\n0};\n'
        'const char* zaMusicPlanJson() { return plan; }\n'
        'const char* zaMusicPlanSha256() { return "%s"; }\n'
        '}\n') % (len(data) + 1, '\n'.join(rows), digest)
open(out, 'w', encoding='ascii', newline='\n').write(text)
print('embedded', len(data), 'bytes', digest)
