"""Embed the two Noto Sans subsets (fonts/*.ttf, OFL 1.1) as C arrays for the title: src/fonts_embedded.inc.
Usage: embed-font.py [fonts dir] [out .inc]. The SHA-256 of each file is pinned in fonts/PROVENANCE.txt and checked here,
so a changed font never gets into a build unnoticed. Deterministic output (byte order, no timestamps)."""
import hashlib
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
fonts = Path(sys.argv[1]) if len(sys.argv) > 1 else root / 'fonts'
out = Path(sys.argv[2]) if len(sys.argv) > 2 else root / 'src' / 'fonts_embedded.inc'
prov = (fonts / 'PROVENANCE.txt').read_text(encoding='utf-8')
pins = dict(re.findall(r'(NotoSans-(?:Regular|Bold)-latin\.ttf)\s+SHA-256\s+([0-9a-f]{64})', prov))
assert len(pins) == 2, pins
parts = ['// GENERATED by tools/embed-font.py from fonts/*.ttf (Noto Sans subsets, OFL 1.1; fonts/PROVENANCE.txt).',
         '// Do not edit. Rebuild with: py -3 port/ui-v2/tools/embed-font.py', '']
for name, ident in (('NotoSans-Regular-latin.ttf', 'kFontRegular'), ('NotoSans-Bold-latin.ttf', 'kFontBold')):
    data = (fonts / name).read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != pins[name]:
        sys.exit('%s: SHA-256 %s does not match PROVENANCE %s' % (name, digest, pins[name]))
    parts.append('// %s, %d bytes, SHA-256 %s' % (name, len(data), digest))
    parts.append('static const unsigned char %s[%d] = {' % (ident, len(data)))
    for i in range(0, len(data), 32):
        parts.append(''.join('%d,' % b for b in data[i:i + 32]))
    parts.append('};')
    parts.append('static const char* const %sSha256 = "%s";' % (ident, digest))
    parts.append('')
out.write_text('\n'.join(parts), encoding='ascii', newline='\n')
print('embedded', out, 'from', fonts)
